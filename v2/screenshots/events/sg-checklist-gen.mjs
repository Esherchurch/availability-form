/* Writes functions/sg-checklist.cjs, the server's copy of the required
   checklist, from the page's (egbc-sg-templates.js): the questions, the
   ticks, the kinds that include another's, and the answers that are flags.
   Run after changing the checklist:  node screenshots/events/sg-checklist-gen.mjs
   sg-ai-unit.test.mjs checks the two agree. */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const V2 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const mod = { exports: {} };
vm.runInNewContext(fs.readFileSync(path.join(V2, 'egbc-sg-templates.js'), 'utf8'), { module: mod });
const T = mod.exports;
const fn = (f) => f.toString();
const out = `/* THE REQUIRED CHECKLIST, the server's copy (for the AI drafts, the host's
   requirements and the warnings): the same ids, words and flags as
   egbc-sg-templates.js. GENERATED by screenshots/events/sg-checklist-gen.mjs -
   do not edit; change the page's copy and run it. */
'use strict';
const CHECKLIST = ${JSON.stringify(T.CHECKLIST, null, 2)};
const FLAGS = ${JSON.stringify(T.FLAGS, null, 2)};
const ALSO = ${JSON.stringify(T.ALSO)};
const SG_KINDS = ${JSON.stringify(T.SG_KINDS)};
const MIN_COVER = ${T.MIN_COVER};
/* the required questions for one event: the core, its kind's (and any it includes), the ticked flags', then the church's own and the host's */
function checklistFor(kind, flags, extra) {
  flags = flags || {};
  let out = CHECKLIST.core.slice();
  if (CHECKLIST[kind] && kind !== 'core') [kind].concat(ALSO[kind] || []).forEach((k) => { out = out.concat(CHECKLIST[k]); });
  FLAGS.forEach((f) => { if (flags[f.id] === true && CHECKLIST[f.id]) out = out.concat(CHECKLIST[f.id]); });
  return out.concat((extra || []).filter((q) => q && q.id && (q.q || q.label)).map((q) => ({ id: q.id, label: q.q || q.label })));
}
${fn(T.answered)}
${fn(T.paedFlag)}
${fn(T.coverOf)}
${fn(T.pounds)}
${fn(T.answerFlags)}
module.exports = { CHECKLIST, FLAGS, ALSO, SG_KINDS, MIN_COVER, checklistFor, answered, paedFlag, coverOf, pounds, answerFlags };
`;
fs.writeFileSync(path.join(V2, 'functions', 'sg-checklist.cjs'), out);
console.log('functions/sg-checklist.cjs written: ' + Object.keys(T.CHECKLIST).map((k) => k + ' ' + T.CHECKLIST[k].length).join(', '));
