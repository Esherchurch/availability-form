/* Builds functions/public-mail-pages.cjs: the pages' own email wording,
   carried to the server so the emails it sends for the public pages
   (F-168, functions/public-mail.js) say exactly what the pages said.
   Events window.

     node screenshots/events/public-mail-pages.mjs           write it
     node screenshots/events/public-mail-pages.mjs --check   fail if stale

   The server deploys only functions/, so it cannot read these files where
   they are. This copies them in, word for word. Run it after changing any
   of them; public-mail.test.mjs runs --check, so a stale copy fails the
   suite rather than sending old words quietly. */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const V2 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = path.join(V2, 'functions', 'public-mail-pages.cjs');

/* In the order a page loads them. egbc-email.js is the main window's: read
   here, never changed. */
export const FILES = ['egbc-email.js', 'egbc-ics.js', 'egbc-events-qr.js', 'egbc-events-checkin.js',
  'egbc-events.js', 'egbc-events-bookings.js', 'egbc-events-forms.js', 'egbc-events-groups.js'];

export function build() {
  const body = FILES.map(f => '  ' + JSON.stringify(f) + ': ' +
    JSON.stringify(fs.readFileSync(path.join(V2, f), 'utf8').replace(/\r\n/g, '\n'))).join(',\n');
  return '/* GENERATED by screenshots/events/public-mail-pages.mjs - do not edit.\n' +
    '   The pages\' own files, word for word, for functions/public-mail.js. */\n' +
    'module.exports = {\n' + body + '\n};\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const want = build();
  /* Line endings aside: git on Windows may give the file either. */
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (process.argv.includes('--check')) {
    if (have !== want) { console.log('STALE: functions/public-mail-pages.cjs - run node screenshots/events/public-mail-pages.mjs'); process.exit(1); }
    console.log('public-mail-pages.cjs is up to date');
  } else {
    fs.writeFileSync(OUT, want);
    console.log('wrote functions/public-mail-pages.cjs (' + Math.round(want.length / 1024) + ' KB)');
  }
}
