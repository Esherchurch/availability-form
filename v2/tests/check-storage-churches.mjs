/* ONE CHURCH'S FILES ARE NOT ANOTHER'S (multi-church step 4 part 1, batch B).
 *
 *   node tests/check-storage-churches.mjs          (from v2/; the firestore and
 *                                                   storage emulators up)
 *   BREAK=1 node tests/check-storage-churches.mjs  the church ruleset without its
 *                                                   gate: must fail
 *   BREAK=kb node tests/check-storage-churches.mjs kb/ uploads for anyone (EGBC's
 *                                                   rule copied as it is): must fail
 *
 * storage.churches.rules (generated by tools/rules-build.mjs from
 * storage.rules) puts every file under churches/{cid}. This checks the part
 * storage-rules.test.mjs cannot, since it runs as one church: two made-up
 * churches, mc-a and mc-b, and people who belong to one of them.
 *   - a member of mc-a reads and writes mc-a's files as storage.rules says;
 *   - never mc-b's, even where storage.rules lets any signed-in person in;
 *   - an admin of mc-a is not an admin of mc-b, even with mc-b in their
 *     claims (the admin test reads mc-b's own users record, and they have none);
 *   - signed out: only what is public to anybody, in either church;
 *   - nothing outside churches/ (EGBC's own top-level files are not in
 *     this ruleset at all).
 */
import fs from 'node:fs';
import { initializeTestEnvironment, assertSucceeds, assertFails } from '@firebase/rules-unit-testing';
import { doc, setDoc } from 'firebase/firestore';
import { ref, uploadBytes, getBytes } from 'firebase/storage';

const cfg = JSON.parse(fs.readFileSync(process.env.EGBC_FIREBASE_CONFIG || 'firebase.json', 'utf8'));
let stRules = fs.readFileSync('storage.churches.rules', 'utf8');
/* BREAK=kb: kb/ uploads for anyone again, as EGBC has until it goes live. */
if (process.env.BREAK === 'kb') stRules = stRules.replace(/^function kbMayUpload\(\) \{.*\}\s*$/m, 'function kbMayUpload() { return true; }');
if (process.env.BREAK === '1') stRules = stRules.replace('function stGate() { return request.auth == null || cid in request.auth.token.churches; }', 'function stGate() { return true; }');
const env = await initializeTestEnvironment({
  projectId: process.env.GCLOUD_PROJECT || 'demo-egbc',
  firestore: { rules: fs.readFileSync('firestore.churches.rules', 'utf8'), host: '127.0.0.1', port: cfg.emulators.firestore.port },
  storage: { rules: stRules, host: '127.0.0.1', port: cfg.emulators.storage.port },
});

const R = [];
const ok = (n, v) => { R.push(v); console.log('  ' + (v ? 'PASS  ' : 'FAIL  ') + n); };
const yes = async (n, p) => { try { await assertSucceeds(p); ok(n, true); } catch (e) { ok(n + '\n          ' + String(e && e.message || e).slice(0, 160), false); } };
const no = async (n, p) => { try { await assertFails(p); ok(n, true); } catch (e) { ok(n + '\n          ' + String(e && e.message || e).slice(0, 160), false); } };
const png = () => new Uint8Array([137, 80, 78, 71]);
const IMG = { contentType: 'image/png' };

try {
  /* Each church's own users record, as the hub keeps it. */
  await env.withSecurityRulesDisabled(async (c) => {
    const db = c.firestore();
    await setDoc(doc(db, 'churches/mc-a/users/u_a_admin'), { uid: 'u_a_admin', status: 'active', masterAdmin: true, adminFor: [] });
    await setDoc(doc(db, 'churches/mc-a/users/u_a_member'), { uid: 'u_a_member', status: 'active', masterAdmin: false, adminFor: [] });
    await setDoc(doc(db, 'churches/mc-b/users/u_b_member'), { uid: 'u_b_member', status: 'active', masterAdmin: false, adminFor: [] });
    const st = c.storage();
    for (const cid of ['mc-a', 'mc-b']) {
      await uploadBytes(ref(st, 'churches/' + cid + '/resources/worship/notes.png'), png(), IMG);
      await uploadBytes(ref(st, 'churches/' + cid + '/banners/hero.png'), png(), IMG);
    }
  });
  const aMember = env.authenticatedContext('u_a_member', { churches: ['mc-a'] }).storage();
  const aAdmin = env.authenticatedContext('u_a_admin', { churches: ['mc-a'] }).storage();
  /* An admin of mc-a whose sign-in also lists mc-b (say, they were added
     to it a minute ago): mc-b's own record says nothing about them. */
  const aAdminBoth = env.authenticatedContext('u_a_admin', { churches: ['mc-a', 'mc-b'] }).storage();
  const out = env.unauthenticatedContext().storage();

  console.log('A member of mc-a, in mc-a');
  await yes('reads a team resource', getBytes(ref(aMember, 'churches/mc-a/resources/worship/notes.png')));
  await yes('  puts up a banner', uploadBytes(ref(aMember, 'churches/mc-a/banners/new.png'), png(), IMG));

  console.log('The same member, in mc-b (storage.rules: "any signed-in person")');
  await no('cannot read mc-b\'s team resource', getBytes(ref(aMember, 'churches/mc-b/resources/worship/notes.png')));
  await no('  cannot put up a banner in mc-b', uploadBytes(ref(aMember, 'churches/mc-b/banners/new.png'), png(), IMG));
  await no('  cannot add a team resource in mc-b', uploadBytes(ref(aMember, 'churches/mc-b/resources/worship/x.png'), png(), IMG));

  console.log('An admin of mc-a');
  await yes('adds an event picture in mc-a', uploadBytes(ref(aAdmin, 'churches/mc-a/events/ev1/p.png'), png(), IMG));
  await no('  not in mc-b', uploadBytes(ref(aAdmin, 'churches/mc-b/events/ev1/p.png'), png(), IMG));
  await no('  nor with mc-b in their sign-in: mc-b\'s own record decides', uploadBytes(ref(aAdminBoth, 'churches/mc-b/events/ev1/p.png'), png(), IMG));

  console.log('Signed out');
  await yes('a public banner, in either church', getBytes(ref(out, 'churches/mc-b/banners/hero.png')));
  await no('  never a team resource', getBytes(ref(out, 'churches/mc-b/resources/worship/notes.png')));
  await no('  nor an event picture added', uploadBytes(ref(out, 'churches/mc-a/events/ev1/q.png'), png(), IMG));

  console.log('kb/ uploads: the Permissions screen\'s answer (H-14), on the sign-in');
  const vid = { contentType: 'video/mp4' };
  const allowedA = env.authenticatedContext('u_a_member', { churches: ['mc-a'], perms: { 'mc-a': ['kbUpload'] } }).storage();
  const allowedB = env.authenticatedContext('u_a_member', { churches: ['mc-a', 'mc-b'], perms: { 'mc-b': ['kbUpload'] } }).storage();
  await yes('somebody allowed uploads to their church\'s How-to pages', uploadBytes(ref(allowedA, 'churches/mc-a/kb/howto-av/clip.mp4'), png(), vid));
  await no('  not a member without the permission', uploadBytes(ref(aMember, 'churches/mc-a/kb/howto-av/clip2.mp4'), png(), vid));
  await no('  not allowed in another church only', uploadBytes(ref(allowedB, 'churches/mc-a/kb/howto-av/clip3.mp4'), png(), vid));
  await no('  never signed out (EGBC\'s open kb/ is not copied)', uploadBytes(ref(out, 'churches/mc-a/kb/howto-av/clip4.mp4'), png(), vid));
  await yes('  and anyone may watch', getBytes(ref(out, 'churches/mc-a/kb/howto-av/clip.mp4')));

  console.log('Outside churches/');
  await no('EGBC\'s top-level files are not in this ruleset', getBytes(ref(aAdmin, 'resources/worship/notes.png')));
  await no('  nor can anyone put one there', uploadBytes(ref(aAdmin, 'banners/new.png'), png(), IMG));
} catch (e) { ok('the run itself: ' + (e && e.stack || e), false); }
finally { await env.cleanup(); }
console.log('\n' + R.filter(Boolean).length + '/' + R.length + ' passed');
process.exit(R.length && R.every(Boolean) ? 0 : 1);
